"""Draw each workflow's shape line as a Mermaid diagram inside its README.

Usage:
  python scripts/build_diagrams.py          write or refresh the diagram in every workflow README
  python scripts/build_diagrams.py --check  exit 1 if any diagram is missing or out of date

The diagram sits right after the **Shape:** line, between two marker comments.
GitHub renders it; edit the shape line, never the diagram.
"""
import re
import sys

from catalog import ROOT, read_front_matter, species_files
from shapes import to_mermaid

START = "<!-- shape diagram: generated by scripts/build_diagrams.py from `shape`; don't edit -->"
END = "<!-- end shape diagram -->"
# inserted as "\n\n" + block + "\n\n" where the file had "\n", so removal is the exact inverse
BLOCK_RE = re.compile(r"\n\n" + re.escape(START) + r".*?" + re.escape(END) + r"\n\n", re.S)


def with_diagram(text, shape):
    block = f"{START}\n```mermaid\n{to_mermaid(shape)}\n```\n{END}\n"
    text = BLOCK_RE.sub("\n", text)
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("**Shape:**"):
            # after the run of bold summary lines that follows the shape
            j = i + 1
            # a bold label with nothing after it introduces the list below it; stop before it
            while j < len(lines) and lines[j].startswith("**") and not re.match(r"^\*\*[^*]+\*\*\s*$", lines[j]):
                j += 1
            return "\n".join(lines[:j] + ["", block.rstrip("\n"), ""] + lines[j:])
    return None


def main():
    check = "--check" in sys.argv
    stale, missing = [], []
    for path in species_files():
        fm, problem = read_front_matter(path)
        if problem:
            sys.exit(f"{path.relative_to(ROOT)}: {problem} (run scripts/validate.py)")
        text = path.read_text()
        new = with_diagram(text, fm["shape"])
        if new is None:
            missing.append(path.relative_to(ROOT))
            continue
        if new != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(new)
    for m in missing:
        print(f"{m}: no **Shape:** line to put the diagram after")
    if check and stale:
        print("Out of date: " + ", ".join(map(str, stale)))
        sys.exit("Run: python scripts/build_diagrams.py")
    if missing:
        sys.exit(1)
    print("Diagrams are up to date." if check else f"Updated {len(stale)} diagram(s).")


if __name__ == "__main__":
    main()
